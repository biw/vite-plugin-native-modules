import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { parse as acornParse } from "acorn";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { build, type Plugin, type Rollup } from "vite";
import nativeFilePlugin from "../src/index.js";

const parse = (code: string) => acornParse(code, { ecmaVersion: "latest", sourceType: "module" });

function outputs(
  result: Rollup.RollupOutput | Rollup.RollupOutput[],
): Array<Rollup.OutputAsset | Rollup.OutputChunk> {
  return (Array.isArray(result) ? result : [result]).flatMap((output) => output.output);
}

function swiftNodeTarget(): string {
  const report = process.report?.getReport?.() as
    | { header?: { glibcVersionRuntime?: string } }
    | undefined;
  const isMusl = process.platform === "linux" && !report?.header?.glibcVersionRuntime;
  return `${process.platform}-${process.arch}${isMusl ? "-musl" : ""}`;
}

function swiftNodeRuntimeSidecarFilename(): string | null {
  if (process.platform === "linux") return "libswiftCore.so.6";
  if (process.platform === "win32") return "swiftCore.dll";
  return null;
}

function writeSwiftNodeAddon(packageDir: string, moduleName: string): string {
  const target = swiftNodeTarget();
  const nativeDirectory =
    process.platform === "darwin" ? packageDir : path.join(packageDir, target);
  const nativeFileName = `${moduleName}.${target}.node`;

  fs.mkdirSync(nativeDirectory, { recursive: true });
  fs.writeFileSync(path.join(nativeDirectory, nativeFileName), Buffer.from("fake native module"));
  const runtimeSidecarFilename = swiftNodeRuntimeSidecarFilename();
  if (runtimeSidecarFilename) {
    fs.writeFileSync(
      path.join(nativeDirectory, runtimeSidecarFilename),
      Buffer.from("fake runtime"),
    );
  }
  return nativeFileName;
}

function writeTargetQualifiedAddon(directory: string, moduleName: string): string {
  const nativeFileName = `${moduleName}.${process.platform}-${process.arch}.node`;
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, nativeFileName), Buffer.from("fake native module"));
  return nativeFileName;
}

function targetQualifiedLoader(moduleName: string): string {
  return `
    import { existsSync } from "node:fs";
    import { createRequire } from "node:module";
    import { fileURLToPath } from "node:url";
    import { dirname, join } from "node:path";

    const require = createRequire(import.meta.url);
    const packageDirectory = dirname(fileURLToPath(import.meta.url));
    const target = \`${"${process.platform}"}-${"${process.arch}"}\`;
    const addonPath = join(packageDirectory, \`${moduleName}.${"${target}"}.node\`);
    if (!existsSync(addonPath)) throw new Error("Native addon unavailable");
    const native = require(addonPath);
    export const operation = native.operation;
  `;
}

function swiftNodeV010Loader(moduleName: string): string {
  return `
    // Generated by swift-node — do not edit
    import { createRequire } from "node:module";
    import { fileURLToPath } from "node:url";
    import path from "node:path";

    const require = createRequire(import.meta.url);
    const __dirname = path.dirname(fileURLToPath(import.meta.url));
    const { existsSync } = require("node:fs");

    function resolveAddonPath(dir, moduleName) {
      const isMusl = process.platform === "linux" && !process.report?.getReport?.().header?.glibcVersionRuntime;
      const target = process.platform + "-" + process.arch + (isMusl ? "-musl" : "");
      const binaryName = moduleName + "." + target + ".node";
      const binaryPath = path.join(dir, ...(process.platform === "darwin" ? [] : [target]), binaryName);
      if (existsSync(binaryPath)) return binaryPath;
      throw new Error("No .node binary found");
    }

    const native = require(resolveAddonPath(__dirname, ${JSON.stringify(moduleName)}));
    export const cloneFile = native.cloneFile;
  `;
}

describe("swift-node support", () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "swift-node-test-"));
  });

  afterEach(() => {
    fs.rmSync(tempDir, { force: true, recursive: true });
  });

  it("removes a preflight guard after rewriting a target-qualified native path", async () => {
    const plugin = nativeFilePlugin() as Plugin;
    (plugin.configResolved as any)({ command: "build", mode: "production" });

    const moduleName = "target_qualified_addon";
    writeTargetQualifiedAddon(tempDir, moduleName);
    const id = path.join(tempDir, "index.mjs");

    const result = (plugin.transform as any).call({ parse }, targetQualifiedLoader(moduleName), id);

    expect(result).toBeDefined();
    expect(result.code).toMatch(
      /createRequire\(import\.meta\.url\)\(["']\.\/target_qualified_addon\.[^"']+-[A-F0-9]{8}\.node["']\)/,
    );
    expect(result.code).not.toContain("require(addonPath)");
    expect(result.code).not.toContain("Native addon unavailable");

    const hashedFilename = result.code.match(
      /\.\/(target_qualified_addon\.[^"']+-[A-F0-9]{8}\.node)/,
    )?.[1];
    expect(hashedFilename).toBeDefined();

    const resolved = await (plugin.resolveId as any).call({} as any, `./${hashedFilename}`, id, {});
    const virtualId = typeof resolved === "string" ? resolved : resolved.id;
    expect(virtualId).toContain("\0native:");

    const loaded = await (plugin.load as any).call({} as any, virtualId);
    expect(loaded).toContain(`./${hashedFilename}`);
  });

  it("bundles a target-qualified loader without its obsolete preflight guard", async () => {
    const packageName = "target-qualified-native-addon";
    const packageDir = path.join(tempDir, "node_modules", packageName, "dist");
    const moduleName = "target_qualified_addon";

    fs.mkdirSync(packageDir, { recursive: true });
    fs.writeFileSync(
      path.join(packageDir, "..", "package.json"),
      JSON.stringify({ name: packageName, main: "./dist/index.mjs", type: "module" }),
    );
    writeTargetQualifiedAddon(packageDir, moduleName);
    fs.writeFileSync(path.join(packageDir, "index.mjs"), targetQualifiedLoader(moduleName));
    const entryPath = path.join(tempDir, "index.mjs");
    fs.writeFileSync(
      entryPath,
      'import { operation } from "target-qualified-native-addon";\nconsole.log(operation);\n',
    );

    const result = (await build({
      root: tempDir,
      logLevel: "silent",
      ssr: { noExternal: [packageName] },
      build: {
        ssr: true,
        write: false,
        rollupOptions: { input: entryPath, output: { format: "es" } },
      },
      plugins: [nativeFilePlugin()],
    })) as Rollup.RollupOutput | Rollup.RollupOutput[];

    const generated = outputs(result);
    expect(
      generated.some(
        (output) =>
          output.type === "asset" &&
          /target_qualified_addon\.[a-z0-9-]+-[A-F0-9]{8}\.node/.test(output.fileName),
      ),
    ).toBe(true);
    expect(
      generated.some(
        (output) =>
          output.type === "chunk" &&
          /target_qualified_addon\.[a-z0-9-]+-[A-F0-9]{8}\.node/.test(output.code),
      ),
    ).toBe(true);
    expect(
      generated.some(
        (output) => output.type === "chunk" && output.code.includes("Native addon unavailable"),
      ),
    ).toBe(false);
  });

  it("rewrites the resolver generated by swift-node 0.1.0", async () => {
    const plugin = nativeFilePlugin() as Plugin;
    (plugin.configResolved as any)({ command: "build", mode: "production" });

    const moduleName = "swift_node_addon";
    const nativeFileName = writeSwiftNodeAddon(tempDir, moduleName);
    const id = path.join(tempDir, "index.mjs");
    const result = (plugin.transform as any).call({ parse }, swiftNodeV010Loader(moduleName), id);

    expect(result).toBeDefined();
    expect(result.code).toMatch(
      /createRequire\(import\.meta\.url\)\(["']\.\/swift_node_addon\.[^"']+-[A-F0-9]{8}\.node["']\)/,
    );
    expect(result.code).not.toContain("require(resolveAddonPath(");

    const hashedFilename = result.code.match(
      /\.\/(swift_node_addon\.[^"']+-[A-F0-9]{8}\.node)/,
    )?.[1];
    expect(hashedFilename).toBeDefined();
    expect(hashedFilename).toContain(nativeFileName.replace(".node", ""));
  });

  it("bundles the loader generated by swift-node 0.1.0", async () => {
    const packageName = "swift-node-addon";
    const packageDir = path.join(tempDir, "node_modules", packageName);
    const moduleName = "swift_node_addon";

    fs.mkdirSync(packageDir, { recursive: true });
    fs.writeFileSync(
      path.join(packageDir, "package.json"),
      JSON.stringify({ name: packageName, main: "index.mjs", type: "module" }),
    );
    writeSwiftNodeAddon(packageDir, moduleName);
    fs.writeFileSync(path.join(packageDir, "index.mjs"), swiftNodeV010Loader(moduleName));
    const entryPath = path.join(tempDir, "index.mjs");
    fs.writeFileSync(
      entryPath,
      'import { cloneFile } from "swift-node-addon";\nconsole.log(cloneFile);\n',
    );

    const result = (await build({
      root: tempDir,
      logLevel: "silent",
      ssr: { noExternal: [packageName] },
      build: {
        ssr: true,
        write: false,
        rollupOptions: { input: entryPath, output: { format: "es" } },
      },
      plugins: [nativeFilePlugin()],
    })) as Rollup.RollupOutput | Rollup.RollupOutput[];

    const generated = outputs(result);
    expect(
      generated.some(
        (output) =>
          output.type === "asset" &&
          /swift_node_addon\.[a-z0-9-]+-[A-F0-9]{8}\.node/.test(output.fileName),
      ),
    ).toBe(true);
    expect(
      generated.some(
        (output) =>
          output.type === "chunk" &&
          /swift_node_addon\.[a-z0-9-]+-[A-F0-9]{8}\.node/.test(output.code),
      ),
    ).toBe(true);

    const runtimeSidecarFilename = swiftNodeRuntimeSidecarFilename();
    if (runtimeSidecarFilename) {
      expect(
        generated.some(
          (output) => output.type === "asset" && output.fileName === runtimeSidecarFilename,
        ),
      ).toBe(true);
    }
  });
});
